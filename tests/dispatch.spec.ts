import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'

test('Search and Routes show the printed company, wave and warehouse zones', async ({ page }) => {
  await page.goto('./')
  const search = page.getByRole('combobox', { name: 'Postcode or route number' })
  await search.fill('M1 5AA')
  await expect(page.getByRole('heading', { name: 'Route 5', exact: true })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Dragonsea · Wave 3 · 08:30 / 09:15' })).toBeVisible()
  await search.fill('M32 9AA')
  await expect(page.getByRole('heading', { name: 'Route 22, Route 37' })).toBeVisible()
  await expect(page.getByText('Crown SDS', { exact: true })).toHaveCount(2)
  await search.fill('M6 5AB')
  await expect(page.getByText('Company and wave need confirmation', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Routes' }).click()
  const filter = page.getByLabel('Filter by route, postcode or company')
  await filter.fill('Forge')
  await expect(page.locator('.route-card')).toHaveCount(9)
  await page.getByRole('link', { name: 'Warehouse plan' }).click()
  await expect(page.getByRole('heading', { name: 'Warehouse plan' })).toBeVisible()
  await expect(page.locator('.warehouse-map li')).toHaveCount(5)
  await expect(page.getByRole('heading', { name: 'Wave 1' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Wave 2' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Wave 3' })).toBeVisible()
  await page.getByText('Routes without a confirmed wave', { exact: true }).click()
  await expect(page.locator('.mapping[open]').getByRole('link')).toHaveCount(8)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('HEIC waybill is read locally and a pickup stays outside the checklist', async ({ page }) => {
  test.setTimeout(120000)
  const requests: string[] = []
  page.on('request', request => { if (request.method() !== 'GET') requests.push(request.url()) })
  await page.goto('./#/deliveries')
  const fixture = fileURLToPath(new URL('./fixtures/synthetic-pickup-label.heic', import.meta.url))
  await page.locator('input[aria-label="Upload screenshot"]').setInputFiles(fixture)
  const row = page.locator('.delivery-edit')
  await expect(row.getByRole('heading', { name: 'JDW99010111991' })).toBeVisible({ timeout: 65000 })
  await expect(row).toHaveCount(1)
  await expect(row.getByText('Pickup · skipped', { exact: true })).toBeVisible()
  const save = page.getByRole('button', { name: 'Save to checklist' })
  await expect(save).toBeDisabled()
  await row.getByRole('combobox', { name: 'Row type' }).selectOption('delivery')
  await expect(row.getByLabel('Full postcode')).toHaveValue('')
  await expect(row.getByRole('combobox', { name: 'Postcodes on label' }).locator('option')).toHaveCount(3)
  await row.getByRole('combobox', { name: 'Postcodes on label' }).selectOption('M1 5AA')
  await expect(row.getByText('Wave 3 · 08:30 / 09:15', { exact: true })).toBeVisible()
  await save.click()
  await expect(page.getByRole('heading', { name: 'Dragonsea' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Route 5' })).toBeVisible()
  expect(requests).toEqual([])
})
